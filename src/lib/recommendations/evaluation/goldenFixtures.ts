const GOLDEN_SHOP_ID = 'golden-eval-shop';

function serviceProfile(
  entityId: string,
  draft: Omit<
    ServiceSemanticProfileV2,
    | 'schemaVersion'
    | 'taxonomyVersion'
    | 'entityType'
    | 'entityId'
    | 'shopId'
    | 'contentHash'
    | 'sourceSnapshot'
    | 'modelId'
    | 'promptVersion'
    | 'classifiedAt'
  >,
  name: string,
): ServiceSemanticProfileV2 {
  return {
    ...draft,
    schemaVersion: '2',
    taxonomyVersion: TAXONOMY_VERSION,
    entityType: 'SERVICE',
    entityId,
    shopId: GOLDEN_SHOP_ID,
    contentHash: `golden-service-${entityId}`,
    sourceSnapshot: { name, description: null, category: 'cuts' },
    modelId: 'golden',
    promptVersion: 'golden',
    classifiedAt: new Date(0).toISOString(),
  };
}

