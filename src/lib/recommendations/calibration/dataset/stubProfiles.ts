export function buildCalibrationStubProfiles(): DryRunStubProfiles {
  const services = new Map<string, ServiceSemanticProfileV2>();
  const products = new Map<string, ProductSemanticProfileV2>();

  for (const service of CALIBRATION_CATALOGUE.services) {
    const ai = SERVICE_AI[service.id];
    if (!ai) throw new Error(`Missing stub AI for service: ${service.id}`);
    services.set(
      service.id,
      buildServiceProfileEnvelope(
        {
          entityId: service.id,
          shopId: CALIBRATION_SHOP_ID,
          name: service.name,
          description: service.description,
          category: service.category,
        },
        ai,
        CALIBRATION_STUB_MODEL,
      ),
    );
  }

  for (const product of CALIBRATION_CATALOGUE.products) {
    const ai = PRODUCT_AI[product.id];
    if (!ai) throw new Error(`Missing stub AI for product: ${product.id}`);
    products.set(
      product.id,
      buildProductProfileEnvelope(
        {
          entityId: product.id,
          shopId: CALIBRATION_SHOP_ID,
          name: product.name,
          description: product.description,
          category: product.category,
        },
        ai,
        CALIBRATION_STUB_MODEL,
      ),
    );
  }

  return { services, products };
}

export function calibrationProductEntries(
  stubs: DryRunStubProfiles,
): Array<{ id: string; profile: ProductSemanticProfileV2 }> {
  return [...stubs.products.entries()].map(([id, profile]) => ({ id, profile }));
}

export function filterStubProfilesByScope(
  stubs: DryRunStubProfiles,
  scopeEntities: import('../types').ScopedCalibrationEntities,
): DryRunStubProfiles {
  const services = new Map<string, ServiceSemanticProfileV2>();
  const products = new Map<string, ProductSemanticProfileV2>();

  for (const serviceId of scopeEntities.serviceIds) {
    const profile = stubs.services.get(serviceId);
    if (profile) services.set(serviceId, profile);
  }
  for (const productId of scopeEntities.productIds) {
    const profile = stubs.products.get(productId);
    if (profile) products.set(productId, profile);
  }

  return { services, products };
}

export function calibrationProductEntriesForScope(
  stubs: DryRunStubProfiles,
  scopeEntities: import('../types').ScopedCalibrationEntities,
): Array<{ id: string; profile: ProductSemanticProfileV2 }> {
  return [...filterStubProfilesByScope(stubs, scopeEntities).products.entries()].map(([id, profile]) => ({
    id,
    profile,
  }));
}

